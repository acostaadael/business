import axios from 'axios';

import buildPaginationQueryOpts from '@/shared/sort/sorts';

import { type IProductFamily } from '@/shared/model/product-family.model';
import type { CrudTableService } from '@/components/crud/crud-table-interface.ts';

const baseApiUrl = 'api/product-families';

export default class ProductFamilyService implements CrudTableService<IProductFamily> {
  public find(id: number): Promise<IProductFamily> {
    return new Promise<IProductFamily>((resolve, reject) => {
      axios
        .get(`${baseApiUrl}/${id}`)
        .then(res => {
          resolve(res.data);
        })
        .catch(err => {
          reject(err);
        });
    });
  }

  public retrieve(paginationQuery?: any): Promise<any> {
    return new Promise<any>((resolve, reject) => {
      axios
        .get(`${baseApiUrl}?${buildPaginationQueryOpts(paginationQuery)}`)
        .then(res => {
          resolve(res);
        })
        .catch(err => {
          reject(err);
        });
    });
  }

  public delete(id: number): Promise<void> {
    return new Promise<any>((resolve, reject) => {
      axios
        .delete(`${baseApiUrl}/${id}`)
        .then(res => {
          resolve(res);
        })
        .catch(err => {
          reject(err);
        });
    });
  }

  public create(entity: IProductFamily): Promise<IProductFamily> {
    return new Promise<IProductFamily>((resolve, reject) => {
      axios
        .post(`${baseApiUrl}`, entity)
        .then(res => {
          resolve(res.data);
        })
        .catch(err => {
          reject(err);
        });
    });
  }

  public update(entity: IProductFamily): Promise<IProductFamily> {
    return new Promise<IProductFamily>((resolve, reject) => {
      axios
        .put(`${baseApiUrl}/${entity.id}`, entity)
        .then(res => {
          resolve(res.data);
        })
        .catch(err => {
          reject(err);
        });
    });
  }

  public partialUpdate(entity: IProductFamily): Promise<IProductFamily> {
    return new Promise<IProductFamily>((resolve, reject) => {
      axios
        .patch(`${baseApiUrl}/${entity.id}`, entity)
        .then(res => {
          resolve(res.data);
        })
        .catch(err => {
          reject(err);
        });
    });
  }
}
